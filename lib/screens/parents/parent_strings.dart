/// Parents Space texts. French / English / Arabic; German uses English,
/// Tamazight uses French.
String pT(BuildContext context, String key, [Map<String, Object?> args = const {}]) {
  final code = Localizations.maybeLocaleOf(context)?.languageCode ?? 'fr';
  final lang = switch (code) {
    'ar' => _ar,
    'en' || 'de' => _en,
    _ => _fr,
  };
  var s = lang[key] ?? _fr[key] ?? key;
  args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}

String subjectName(BuildContext context, String key) {
  final s = pT(context, 'subj_$key');
  return s.startsWith('subj_') ? key : s;
}

String feedTitle(BuildContext context, FeedItem f) {
  switch (f.type) {
    case 'lesson':
      return pT(context, 'feed_lesson', {'subject': subjectName(context, f.ref)});
    case 'game':
      String g;
      try {
        g = gameTitle(tr(context), f.ref);
      } catch (_) {
        g = f.ref;
      }
      return pT(context, 'feed_game', {'game': g});
    case 'drawing':
      return pT(context, 'feed_drawing');
    case 'badge':
      return pT(context, 'feed_badge');
    default:
      return pT(context, 'feed_other');
  }
}

String feedSub(BuildContext context, FeedItem f) => pT(context, 'fsub_${f.type}');

